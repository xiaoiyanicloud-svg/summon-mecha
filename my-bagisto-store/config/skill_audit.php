<?php

/**
 * 审核与发布闸门 —— v3.4 步骤 6/10。
 *
 * 闸门定义放配置：**哪几层必须过，才允许发布**。
 * 放配置而不是硬编码，是因为 L1 仿真层依赖一个**外部仿真器**，接入时间不受平台控制。
 */
return [
    /*
    |--------------------------------------------------------------------------
    | 发布闸门：必须通过的审核层
    |--------------------------------------------------------------------------
    | 1 = L0 机审（格式/权限/内容）  2 = L1 仿真预跑  3 = L2 人审
    |
    | ⚠ 当前默认 `1,3`，**不含 2** —— 原因不是"L1 不必做"，而是**仿真器尚未接入**
    |   （外部工具，见 skill-dev-step6.md「诚实边界」）。
    |   把一个跑不起来的层写进闸门，结果是所有技能都发布不了：那是拿整条供给链
    |   去换一个好看的勾。所以这里**如实排除**，并且：
    |
    |     ① 界面把 L1 显式标成「未接入（不参与闸门）」，**不伪装成"已通过"**；
    |     ② 仿真器接入后，把 2 加回来即可 —— 只改这一个环境变量，不动代码。
    |
    | 反向也成立：若你把未接入的层写进这里，结果是 fail-closed（谁都发布不了）。
    | 那是安全的方向，不是 bug。所以这里**不提供"自动跳过未接入层"的魔法** ——
    | 跳过必须是一次显式的配置改动，留下痕迹。
    */
    'required_layers' => array_values(array_filter(array_map(
        'intval',
        explode(',', (string) env('SKILL_AUDIT_REQUIRED_LAYERS', '1,3'))
    ))),

    /*
    |--------------------------------------------------------------------------
    | 各层的人话名
    |--------------------------------------------------------------------------
    */
    'layer_labels' => [
        1 => 'L0 机审',
        2 => 'L1 仿真预跑',
        3 => 'L2 人审',
    ],

    /*
    |--------------------------------------------------------------------------
    | 各层"是否已接入"的声明
    |--------------------------------------------------------------------------
    | ⚠ 只用于**界面如实展示**，**不参与闸门判定**。
    |   一个层没接入时，界面必须说"未接入"，不能说"通过" ——
    |   这与内容安全的「没查 ≠ 合规」是同一条原则。
    |
    | 仿真器接入后，把 2 改成 true，并把 2 加进 required_layers。
    */
    'layers_available' => [
        1 => true,
        2 => false,
        3 => true,
    ],
];
